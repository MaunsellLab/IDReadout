function cfg = configureNoiseMixture(cfg,independentFraction,varianceExponent)
%CONFIGURENOISEMIXTURE Add independent response-scaled mechanism noise.
independentFraction=double(independentFraction);
varianceExponent=double(varianceExponent);
assert(isscalar(independentFraction)&&isfinite(independentFraction)&& ...
  independentFraction>=0&&independentFraction<=1, ...
  'IndependentNoiseFraction must be between zero and one.');
assert(isscalar(varianceExponent)&&isfinite(varianceExponent)&& ...
  varianceExponent>=0, ...
  'NoiseVarianceExponent must be a finite nonnegative scalar.');
cfg.independentNoiseFraction=independentFraction;
cfg.noiseVarianceExponent=varianceExponent;
if independentFraction>0
  cfg.modelVersion=string(cfg.modelVersion)+sprintf( ...
    '-independent-noise-lambda%.4g-var-exp%.4g', ...
    independentFraction,varianceExponent);
end
end
