function diagnostic = sharedRDKNoiseSweep(cache,fit,varargin)
%SHAREDRDKNOISESWEEP Sweep pre-max noise and cross-RDK noise correlation.

p=inputParser;
p.addParameter('TrialMask',fit.trialMask,@(x)islogical(x)||isnumeric(x));
p.addParameter('Domain',"IDR",@(x)isstring(x)||ischar(x));
p.addParameter('Animal',"Meetz",@(x)isstring(x)||ischar(x));
p.addParameter('ProbeOffsetDeg',25,@(x)isnumeric(x)&&isscalar(x)&&isfinite(x));
p.addParameter('StepMagnitudePC',23,@(x)isnumeric(x)&&isscalar(x)&&isfinite(x));
p.addParameter('NoiseSDGridPC',[0 5 10 15 20 25], ...
  @(x)isnumeric(x)&&isvector(x)&&~isempty(x)&&all(isfinite(x))&&all(x>=0));
p.addParameter('RDKNoiseCorrelationGrid',0:0.25:1, ...
  @(x)isnumeric(x)&&isvector(x)&&~isempty(x)&&all(isfinite(x))&& ...
  all(x>=0)&&all(x<=1));
p.addParameter('NDraws',64,@(x)isnumeric(x)&&isscalar(x)&&x>=2&&mod(x,1)==0);
p.addParameter('MinimumTrials',500,@(x)isnumeric(x)&&isscalar(x)&&x>=20);
p.addParameter('MinimumSessions',5,@(x)isnumeric(x)&&isscalar(x)&&x>=2);
p.parse(varargin{:});

rhoGrid=unique(double(p.Results.RDKNoiseCorrelationGrid(:)),'stable');
byCorrelation=cell(numel(rhoGrid),1); sweep=table(); bestByCorrelation=table();
for k=1:numel(rhoGrid)
  D=maxpoolfit.noisePlacementSweep(cache,fit, ...
    'TrialMask',p.Results.TrialMask, ...
    'Domain',p.Results.Domain,'Animal',p.Results.Animal, ...
    'ProbeOffsetDeg',p.Results.ProbeOffsetDeg, ...
    'StepMagnitudePC',p.Results.StepMagnitudePC, ...
    'NoiseSDGridPC',p.Results.NoiseSDGridPC, ...
    'RDKNoiseCorrelation',rhoGrid(k),'UsePairedRDKDraws',true, ...
    'NDraws',p.Results.NDraws, ...
    'MinimumTrials',p.Results.MinimumTrials, ...
    'MinimumSessions',p.Results.MinimumSessions);
  byCorrelation{k}=D;
  if isempty(sweep), sweep=D.sweep; else, sweep=[sweep;D.sweep]; end %#ok<AGROW>
  if ~isempty(D.bestFeasibleRatioRow)
    if isempty(bestByCorrelation), bestByCorrelation=D.bestFeasibleRatioRow;
    else, bestByCorrelation=[bestByCorrelation;D.bestFeasibleRatioRow]; end %#ok<AGROW>
  end
end

bestRatioRow=bestRow(sweep,'ratioRMSE',true);
bestAbsoluteGainRow=bestRow(sweep,'postFlipAbsoluteGainRMSE',true);
bestLogLossRow=bestRow(sweep,'postFlipLogLoss',true);
first=byCorrelation{1}; selection=first.selection;
selection.rdkNoiseCorrelationGrid=rhoGrid;
selection.noiseSDGridPC=unique(double(p.Results.NoiseSDGridPC(:)),'stable');
diagnostic=struct('sweep',sweep,'targets',first.targets, ...
  'selection',selection,'trialIdx',first.trialIdx, ...
  'observedAccuracy',first.observedAccuracy, ...
  'currentNoiseSDPC',first.currentNoiseSDPC, ...
  'bestFeasibleByCorrelation',bestByCorrelation, ...
  'bestFeasibleRatioRow',bestRatioRow, ...
  'bestFeasibleAbsoluteGainRow',bestAbsoluteGainRow, ...
  'bestFeasibleLogLossRow',bestLogLossRow, ...
  'byCorrelation',{byCorrelation},'adaptation',fit.adaptation, ...
  'nNoiseDraws',p.Results.NDraws,'modelVersion',fit.modelVersion, ...
  'noiseConstruction', ...
    "zRDK = sqrt(rho)*zCommon + sqrt(1-rho)*zIndependent", ...
  'pairedDrawContract',true,'createdAt',datetime('now'));
end

function row=bestRow(S,variable,requireFeasible)
q=isfinite(S.(variable));
if requireFeasible, q=q&S.downstreamFeasible; end
if ~any(q), row=S([],:); return; end
objective=S.(variable); objective(~q)=inf; [~,k]=min(objective); row=S(k,:);
end
