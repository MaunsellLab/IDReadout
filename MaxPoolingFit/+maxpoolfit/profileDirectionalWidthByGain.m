function result=profileDirectionalWidthByGain(cache,baseFit,varargin)
%PROFILEDIRECTIONALWIDTHBYGAIN Fit effective directional width to gains.
%
% At each width, design-group noise SDs are reoptimized by trial-level
% choice likelihood. Width selection is then based on equal-cell changed-side
% drift and probe gain RMSE in the requested target groups.

p=inputParser;
p.addParameter('DirectionalWidthGridDeg',[10 15 20 25 30 37.5 45 60], ...
  @(x)isnumeric(x)&&isvector(x)&&~isempty(x)&&all(isfinite(x))&&all(x>0));
p.addParameter('TargetGroups',["IDQ-randomized" "IDS"], ...
  @(x)isstring(x)||iscellstr(x)||ischar(x));
p.addParameter('NDraws',64,@(x)isnumeric(x)&&isscalar(x)&&x>=2&&mod(x,1)==0);
p.addParameter('MinimumGainSessions',3, ...
  @(x)isnumeric(x)&&isscalar(x)&&x>=1&&mod(x,1)==0);
p.parse(varargin{:});
maxpoolfit.validateCache(cache);
required={'trialGroup','trialMask','adaptationByGroup','config'};
assert(all(isfield(baseFit,required)),'A completed design-group fit is required.');
assert(numel(baseFit.trialGroup)==height(cache.trials), ...
  'Design-group labels do not match the cache.');

grid=unique(double(p.Results.DirectionalWidthGridDeg(:)),'stable');
if ischar(p.Results.TargetGroups)
  targetGroups=string(p.Results.TargetGroups);
else
  targetGroups=unique(string(p.Results.TargetGroups(:)),'stable');
end
trialGroup=string(baseFit.trialGroup(:));
assert(all(ismember(targetGroups,unique(trialGroup(baseFit.trialMask)))), ...
  'One or more TargetGroups have no selected primary trials.');
workCache=cache; workCache.trials.domain=trialGroup;
fits=cell(numel(grid),1); predictions=cell(numel(grid),1);
overallRows=cell(numel(grid),12); groupProfile=table(); gainProfile=table();

for k=1:numel(grid)
  cfg=baseFit.config; cfg.sigmaMTDeg=grid(k); cfg.sigmaAdaptDeg=grid(k);
  cfg.verbose=false;
  cfg.modelVersion=string(baseFit.modelVersion)+"-directional-width-gain-profile";
  fprintf('Directional width %g deg (%d/%d)\n',grid(k),k,numel(grid));
  fit=maxpoolfit.fitDesignGroupModel(cache,cfg,trialGroup, ...
    baseFit.adaptationByGroup,'TrialMask',baseFit.trialMask, ...
    'NDraws',p.Results.NDraws);
  prediction=maxpoolfit.predictDesignGroupModel(cache,fit,cfg, ...
    'TrialMask',baseFit.trialMask,'NDraws',p.Results.NDraws);
  fits{k}=fit; predictions{k}=prediction;
  comparison=maxpoolfit.gainComparison(workCache,prediction,prediction, ...
    'TrialMask',baseFit.trialMask);
  G=comparison.summary;
  G=G(ismember(string(G.source),["observed" "primary domain noise"]),:);
  G.source(string(G.source)=="primary domain noise")="directional-width model";
  G.directionalWidthDeg=repmat(grid(k),height(G),1);
  gainProfile=appendRows(gainProfile,G);
  H=fit.groupFit; H.directionalWidthDeg=repmat(grid(k),height(H),1);
  groupProfile=appendRows(groupProfile,H);
  M=gainMetrics(G,targetGroups,p.Results.MinimumGainSessions);
  targetQ=ismember(string(H.analysisGroup),targetGroups);
  overallRows(k,:)={grid(k),fit.logLikelihood,sum(H.logLikelihood(targetQ)), ...
    sum(H.evalCount),fit.nTrials,M.nConditions,M.coefficientRMSE,M.gainRMSE, ...
    M.driftGainRMSE,M.probeGainRMSE,M.ratioRMSE,mean(H.noiseSDPC(targetQ))};
end

overallProfile=cell2table(overallRows,'VariableNames',{ ...
  'directionalWidthDeg','logLikelihood','targetLogLikelihood','evalCount', ...
  'nTrials','nGainConditions','changedCoefficientRMSE','changedGainRMSE', ...
  'changedDriftGainRMSE','changedProbeGainRMSE','ratioRMSE', ...
  'meanTargetNoiseSDPC'});
overallProfile.deltaLogLFromChoiceBest=overallProfile.logLikelihood- ...
  max(overallProfile.logLikelihood);
overallProfile.deltaTargetLogLFromChoiceBest=overallProfile.targetLogLikelihood- ...
  max(overallProfile.targetLogLikelihood);
[~,gainRow]=min(overallProfile.changedGainRMSE);
[~,choiceRow]=max(overallProfile.targetLogLikelihood);

result=struct('overallProfile',overallProfile,'groupProfile',groupProfile, ...
  'gainProfile',gainProfile,'fits',{fits},'predictions',{predictions}, ...
  'directionalWidthGridDeg',grid,'targetGroups',targetGroups, ...
  'minimumGainSessions',p.Results.MinimumGainSessions, ...
  'nNoiseDraws',p.Results.NDraws, ...
  'gainOptimalWidthDeg',overallProfile.directionalWidthDeg(gainRow), ...
  'choiceOptimalWidthDeg',overallProfile.directionalWidthDeg(choiceRow), ...
  'gainOptimalFit',fits{gainRow},'gainOptimalPrediction',predictions{gainRow}, ...
  'choiceOptimalFit',fits{choiceRow}, ...
  'choiceOptimalPrediction',predictions{choiceRow}, ...
  'gainObjective',"equal weight per retained animal-design-offset cell; "+ ...
    "equal weight for changed drift and changed probe gains", ...
  'createdAt',datetime('now'));
end

function M=gainMetrics(G,targetGroups,minSessions)
O=sortrows(G(ismember(string(G.domain),targetGroups)& ...
  string(G.source)=="observed",:),{'domain','animal','probeOffsetDeg'});
P=sortrows(G(ismember(string(G.domain),targetGroups)& ...
  string(G.source)=="directional-width model",:), ...
  {'domain','animal','probeOffsetDeg'});
assert(height(O)==height(P)&&isequal(string(O.domain),string(P.domain))&& ...
  isequal(string(O.animal),string(P.animal))&& ...
  isequal(O.probeOffsetDeg,P.probeOffsetDeg), ...
  'Observed and predicted target gain cells do not align.');
q=O.nSessions>=minSessions;
assert(any(q),'No target gain cells meet MinimumGainSessions.');
driftGain=P.changedDriftGain(q)-O.changedDriftGain(q);
probeGain=P.changedProbeGain(q)-O.changedProbeGain(q);
driftCoefficient=P.changedDriftCoefficientPerPC(q)- ...
  O.changedDriftCoefficientPerPC(q);
probeCoefficient=P.changedProbeCoefficientPerPC(q)- ...
  O.changedProbeCoefficientPerPC(q);
ratio=P.changedProbeOverDrift(q)-O.changedProbeOverDrift(q);
M=struct('nConditions',sum(q), ...
  'coefficientRMSE',sqrt(mean([driftCoefficient.^2;probeCoefficient.^2])), ...
  'gainRMSE',sqrt(mean([driftGain.^2;probeGain.^2])), ...
  'driftGainRMSE',sqrt(mean(driftGain.^2)), ...
  'probeGainRMSE',sqrt(mean(probeGain.^2)), ...
  'ratioRMSE',sqrt(mean(ratio.^2)));
end

function A=appendRows(A,B)
if width(A)==0, A=B; else, A=[A;B]; end
end
