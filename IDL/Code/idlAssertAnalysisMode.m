function idlAssertAnalysisMode(A,twoAllocationMode)
% Reject mixed-style pooling, including explicitly supplied result inputs.
H = A.sessionHeader;
assert(isfield(H,'twoAllocationMode') && ...
  logical(H.twoAllocationMode)==twoAllocationMode, ...
  'idlAssertAnalysisMode:Style', ...
  'Session style does not match TwoAllocationMode; regenerate/select its analysis.');
expected = [100 75 62.5 50];
if twoAllocationMode, expected = [100 50]; end
assert(isequal(sort(unique(round(double(A.trialTable.unsignedAllocPC),6)), ...
  'descend')',expected), 'idlAssertAnalysisMode:Allocations', ...
  'Session trial allocations do not match its analysis style.');
end
