function report = validateIDLFirstSession(sourcePath)
% validateIDLFirstSession  Regression checks for the first recorded IDL session.
%
% report = validateIDLFirstSession(sourcePath)
%
% This is deliberately specific to IDR5_Meetz_20260911.mat. It verifies the
% trial-derived configuration changes and the compact data contract, then
% exercises both versions of the joint psychometric fit.

A = makeIDLSessionAnalysis(sourcePath);
assert(strcmp(A.sourceSessionID, "IDR5_Meetz_20260911"), ...
  'validateIDLFirstSession:UnexpectedSession', ...
  'This regression check is specific to IDR5_Meetz_20260911.');
assert(A.nTrialsTotal == 2632, ...
  'validateIDLFirstSession:TotalTrialCount', ...
  'Expected 2,632 total trials in the first recorded session.');
assert(A.nAnalysisTrials == 1968, ...
  'validateIDLFirstSession:AnalysisTrialCount', ...
  'Expected 1,968 certified correct/wrong analysis trials.');

allocationPC = [100; 75; 62.5; 50];
nTrials = arrayfun(@(a) sum(abs(A.trialTable.unsignedAllocPC - a) < 1e-6), ...
  allocationPC);
assert(all(nTrials == 492), ...
  'validateIDLFirstSession:AllocationBalance', ...
  'Expected 492 analysis trials at each unsigned allocation.');
assert(height(A.configurationTable) == 3, ...
  'validateIDLFirstSession:ConfigurationEpochCount', ...
  'Expected three trial-derived configuration epochs.');
assert(isequal(A.configurationTable.firstSourceTrial(:), [1; 896; 937]), ...
  'validateIDLFirstSession:ConfigurationEpochStarts', ...
  'Expected configuration epochs to begin at trials 1, 896, and 937.');
assert(height(A.stepTable) == 60 && ...
    sum(A.stepTable.nAnalysisTrials) == A.nAnalysisTrials, ...
  'validateIDLFirstSession:StepTable', ...
  'The configured step table does not account for the first session.');
assert(isequal(size(A.changeNoiseByFrameTrial), [30 1968 2]), ...
  'validateIDLFirstSession:ChangeNoiseSize', ...
  'Unexpected change-side compact noise dimensions.');
assert(isequal(size(A.noChangeNoiseByFrameTrial), [30 1968 2]), ...
  'validateIDLFirstSession:NoChangeNoiseSize', ...
  'Unexpected no-change-side compact noise dimensions.');

zeroLapseFit = fitIDLSessionPsychometrics(A.trialTable, 'FixedLapse', 0);
freeLapseFit = fitIDLSessionPsychometrics(A.trialTable);
assert(zeroLapseFit.exitflag > 0 && freeLapseFit.exitflag > 0, ...
  'validateIDLFirstSession:FitConvergence', ...
  'At least one joint psychometric fit did not converge.');
assert(all(isfinite(zeroLapseFit.thresholdTable.threshold)), ...
  'validateIDLFirstSession:InvalidThreshold', ...
  'The zero-lapse fit returned a nonfinite threshold.');
expectedThreshold = [10.394; 12.763; 14.156; 14.007];
assert(all(abs(zeroLapseFit.thresholdTable.threshold - expectedThreshold) < 0.02) && ...
    abs(zeroLapseFit.betaWeibull - 1.810) < 0.01, ...
  'validateIDLFirstSession:UnexpectedFit', ...
  'The joint zero-lapse fit does not reproduce the reference result.');
assert(freeLapseFit.lapse < 1e-3 && ...
    abs(freeLapseFit.negLogLikelihood - zeroLapseFit.negLogLikelihood) < 1e-3, ...
  'validateIDLFirstSession:UnexpectedLapseFit', ...
  'The shared-lapse diagnostic does not reproduce the reference result.');

report = struct();
report.sourceSessionID = A.sourceSessionID;
report.nTrialsTotal = A.nTrialsTotal;
report.nAnalysisTrials = A.nAnalysisTrials;
report.allocationPC = allocationPC;
report.nTrialsByAllocation = nTrials;
report.configurationTable = A.configurationTable;
report.zeroLapseFit = zeroLapseFit;
report.freeLapseFit = freeLapseFit;

fprintf(['validateIDLFirstSession: passed (%d analysis trials, ' ...
  '%d configuration epochs).\n'], ...
  A.nAnalysisTrials, height(A.configurationTable));
end
