function savePairedProbeTemporalMaxFigures(handles,outputDir)
% SAVEPAIREDPROBETEMPORALMAXFIGURES  Export temporal-max figures as PDFs.

names={'PairedProbe_TemporalMax_Gains.pdf', ...
    'PairedProbe_TemporalMax_OperatingPoints.pdf', ...
    'PairedProbe_TemporalMax_WinnerDynamics.pdf', ...
    'PairedProbe_TemporalMax_Decomposition.pdf', ...
    'PairedProbe_TemporalMax_WinnerDirectionDistributions.pdf', ...
    'PairedProbe_TemporalMax_WinnerDirectionContributions.pdf'};
for k=1:min(numel(handles),numel(names))
    exportgraphics(handles(k),fullfile(outputDir,names{k}),'ContentType','vector');
end
end
