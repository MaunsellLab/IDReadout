function sim = simulateDriftTemplateCondition(bank,offsetDeg,yoked,step, ...
    baseDriftCoherence,cancellationFraction,internalNoiseSD,cfg)
% SIMULATEDRIFTTEMPLATECONDITION  Choices, gains, and winner diagnostics.

pcfg=cfg.PairedConfig;
model=buildDriftTemplateResponses(bank,offsetDeg,yoked,baseDriftCoherence, ...
    cancellationFraction,internalNoiseSD,cfg);
responseChanged=bsxfun(@plus,model.responseChangedBase, ...
    single(step)*model.W(1,:));
[valueChanged,winnerChanged]=max(responseChanged,[],2);
[valueNoChange,winnerNoChange]=max(model.responseNoChange,[],2);
correct=valueChanged>valueNoChange;
fit=fitProbitIRLS(model.predictors,correct);

if yoked
    cTotal=[0;1]; cPer=[0;0.5]; yokingName='Yoked';
else
    cTotal=[0;1;1]; cPer=[0;0.5;0.5]; yokingName='Independent';
end
covariance=fit.covariance;
gain=struct('drift',fit.beta(1), ...
    'driftSE',sqrt(max(covariance(1,1),0)), ...
    'probeTotal',cTotal'*fit.beta, ...
    'probeTotalSE',sqrt(max(cTotal'*covariance*cTotal,0)), ...
    'probePerStream',cPer'*fit.beta, ...
    'probePerStreamSE',sqrt(max(cPer'*covariance*cPer,0)));

winners=classifyDenseWinners(winnerChanged,winnerNoChange, ...
    bank.directionsDeg,model.streamDirections,pcfg.WinnerAssociationRadiusDeg);
winnerDirection=computeWinnerDirectionDiagnostic(winnerChanged,winnerNoChange, ...
    bank.directionsDeg,model.W,cfg.WinnerDirectionBinWidthDeg);

driftDecomp=decomposeStreamInfluence(responseChanged,model.responseNoChange, ...
    model.W(1,:),pcfg.CounterfactualPerturbation);
if yoked
    probePair=decomposeStreamInfluence(responseChanged,model.responseNoChange, ...
        model.W(2,:)+model.W(3,:),pcfg.CounterfactualPerturbation);
    probePer=scaleDecomposition(probePair,0.5);
else
    probe1=decomposeStreamInfluence(responseChanged,model.responseNoChange, ...
        model.W(2,:),pcfg.CounterfactualPerturbation);
    probe2=decomposeStreamInfluence(responseChanged,model.responseNoChange, ...
        model.W(3,:),pcfg.CounterfactualPerturbation);
    probePer=averageDecompositions(probe1,probe2);
end

sim=struct('offsetDeg',offsetDeg,'yoked',yoked,'yoking',yokingName, ...
    'baseDriftCoherence',baseDriftCoherence, ...
    'cancellationFraction',cancellationFraction,'stepCoherence',step, ...
    'residualDriftCoherence',model.residualDriftCoherence, ...
    'cancelledDriftCoherence',model.cancelledDriftCoherence, ...
    'performance',mean(correct),'fit',fit,'gain',gain,'winners',winners, ...
    'winnerDirection',winnerDirection);
sim.decomposition.drift=driftDecomp;
sim.decomposition.probePerStream=probePer;
end

function d=scaleDecomposition(d,scale)
fields={'changedFixed','changedSwitch','noChangeFixed','noChangeSwitch', ...
    'decisionFixed','decisionSwitch','decisionTotal'};
for k=1:numel(fields), d.(fields{k})=scale*d.(fields{k}); end
end

function d=averageDecompositions(a,b)
d=a;
fields={'changedFixed','changedSwitch','noChangeFixed','noChangeSwitch', ...
    'decisionFixed','decisionSwitch','decisionTotal', ...
    'changedSwitchProbability','noChangeSwitchProbability'};
for k=1:numel(fields), d.(fields{k})=0.5*(a.(fields{k})+b.(fields{k})); end
end
