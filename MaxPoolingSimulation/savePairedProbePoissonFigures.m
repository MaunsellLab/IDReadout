function savePairedProbePoissonFigures(handles,outputDir)
% SAVEPAIREDPROBEPOISSONFIGURES  Export the four stage figures as PDFs.

names={'PairedProbe_PoissonVariance_Gains.pdf', ...
    'PairedProbe_PoissonVariance_OperatingPoints.pdf', ...
    'PairedProbe_PoissonVariance_Winners.pdf', ...
    'PairedProbe_PoissonVariance_RateDiagnostics.pdf'};
for k=1:min(numel(handles),numel(names))
    exportgraphics(handles(k),fullfile(outputDir,names{k}), ...
        'ContentType','vector');
end
end
