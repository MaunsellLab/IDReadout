function savePairedProbeDriftTemplateFigures(handles,outputDir)
% SAVEPAIREDPROBEDRIFTTEMPLATEFIGURES  Export drift-template PDFs.

names={'PairedProbe_DriftTemplate_Gains.pdf', ...
    'PairedProbe_DriftTemplate_OperatingPoints.pdf', ...
    'PairedProbe_DriftTemplate_WinnerFractions.pdf', ...
    'PairedProbe_DriftTemplate_FixedWinnerTotals.pdf', ...
    'PairedProbe_DriftTemplate_WinnerDirectionDistributions.pdf', ...
    'PairedProbe_DriftTemplate_WinnerDirectionContributions.pdf'};
for k=1:min(numel(handles),numel(names))
    exportgraphics(handles(k),fullfile(outputDir,names{k}),'ContentType','vector');
end
end
