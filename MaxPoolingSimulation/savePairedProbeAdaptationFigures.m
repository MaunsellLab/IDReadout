function savePairedProbeAdaptationFigures(handles,outputDir)
% SAVEPAIREDPROBEADAPTATIONFIGURES  Export adaptation-stage vector PDFs.
names={'PairedProbe_Adaptation_Gains.pdf', ...
    'PairedProbe_Adaptation_OperatingPoints.pdf', ...
    'PairedProbe_Adaptation_WinnerFractions.pdf', ...
    'PairedProbe_Adaptation_FixedWinnerTotals.pdf', ...
    'PairedProbe_Adaptation_WinnerDirectionDistributions.pdf', ...
    'PairedProbe_Adaptation_WinnerDirectionContributions.pdf', ...
    'PairedProbe_Adaptation_EmpiricalThresholdConstraints.pdf'};
for k=1:min(numel(handles),numel(names))
    exportgraphics(handles(k),fullfile(outputDir,names{k}),'ContentType','vector');
end
end
