function current = idjHasTopUpExclusion(A)
% idjHasTopUpExclusion  True for a compact analysis using the current filter.
% Require the extraction contract as well as the actual retained-trial flags.
current = isstruct(A) && isscalar(A) && isfield(A,'version') && ...
  isnumeric(A.version) && isscalar(A.version) && A.version>=2 && ...
  isfield(A,'topUpTrialsExcluded') && isequal(A.topUpTrialsExcluded,true) && ...
  isfield(A,'nExcludedTopUpTrials') && ...
  isfield(A,'trialTable') && istable(A.trialTable) && ...
  ismember('topUpTrial',A.trialTable.Properties.VariableNames);
if current
  flags = double(A.trialTable.topUpTrial);
  current = iscolumn(flags) && numel(flags)==height(A.trialTable) && ...
    all(isfinite(flags)) && all(flags==0);
end
end
